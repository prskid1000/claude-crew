#Requires -Version 7
<#
bossy-generic.tests.ps1: bossy.ps1 on neutral and custom config: setup -Allow (vendor CLI + OS allows generated from the adapters), learn -Read of LESSONS.local.md.
Usage: pwsh -NoProfile -File <kit>/tests/bossy-generic.tests.ps1 (or tests/kit-tests.ps1 -Area bossy-generic).
Exit codes: 0 pass · 1 a check failed.
#>
. (Join-Path $PSScriptRoot 'harness.ps1')
$k = New-TestKit bossygen; $O = Join-Path $k 'skills/bossy/bossy.ps1'
# setup -Allow: host + report + OS entries generated, own entries kept, stale generated ones dropped, idempotent
$al = Invoke-PsTest allow @'
$null = . $args[0] 6>$null; $sl = Join-Path $KitConf.Kit 'settings.local.json'
[IO.File]::WriteAllText($sl, '{ "autoMemoryDirectory": "x", "permissions": { "allow": ["Bash(mine *)", "PowerShell(gh pr *)"] } }')
$script:HostType = 'gitlab'; $KitConf.ReportType = 'gdocs'; $KitIsWindows = $true
$r1 = Set-KitAllowList; $s = Get-Content $sl -Raw | ConvertFrom-Json; $a = @($s.permissions.allow)
"gitlab:$($a -contains 'Bash(mine *)' -and $a -notcontains 'PowerShell(gh pr *)' -and $a -contains 'PowerShell(glab mr *)' -and $a -contains 'PowerShell(gws drive files export *)' -and $a -contains 'PowerShell(& *.claude\skills\*)' -and $s.autoMemoryDirectory -eq 'x' -and $r1 -match '^allow: 7 generated entries')"
"same:$(-not (Set-KitAllowList))"
$script:HostType = 'bitbucket'; $KitConf.ReportType = 'markdown'; $KitIsWindows = $false; $null = Set-KitAllowList; $a = @((Get-Content $sl -Raw | ConvertFrom-Json).permissions.allow)
"neutral:$(($a -join '|') -eq 'Bash(mine *)')"
$script:HostType = 'github'; $null = Set-KitAllowList; $a = @((Get-Content $sl -Raw | ConvertFrom-Json).permissions.allow)
"github:$($a -contains 'PowerShell(gh pr *)' -and $a -notcontains 'PowerShell(glab mr *)')"
[IO.File]::WriteAllText($sl, '{ bad'); "badjson:$((Set-KitAllowList) -match 'not valid JSON' -and (Get-Content $sl -Raw) -eq '{ bad')"
'@ @($O)
Expect-Each $al 'setup -Allow: #' 'gitlab', 'same', 'neutral', 'github', 'badjson' -Show 6
$sj = Get-Content (Join-Path $src 'settings.json') -Raw
Expect 'settings.json: no vendor CLI or Windows-path allows (generated by setup -Allow)' ($sj -notmatch '\((glab|gh|gws) ' -and $sj -notmatch '\.claude\\\\skills')
Remove-TestKit $k
Complete-Tests
