def org_rules():
    """[(file name, text)] of the org rules (rules/*.local.md; local only, never pushed)."""
    return [(p.name, p.read_text(encoding='utf-8').replace('\r\n', '\n')) for p in sorted((KIT / 'rules').glob('*.local.md'))]

def split_rule(text, cap):
    """Chunks of whole lines, each <= cap UTF-8 bytes."""
    parts, cur = [], ''
    for line in text.splitlines(keepends=True):
        if cur and len((cur + line).encode('utf-8')) > cap:
            parts.append(cur)
            cur = ''
        cur += line
    return parts + ([cur] if cur else [])

def workspace_files():
    """{workspace path: text} the deploy writes besides the .codex / .agents copies."""
    kit = KIT.as_posix()
    out = {".codex/config.toml": codex_config_text(kit), ".agents/hooks.json": gravity_hooks_text(kit, windows()),
      "GEMINI.md": (KIT / "GEMINI.md").read_text(encoding="utf-8"), "AGENTS.md": (KIT / "AGENTS.md").read_text(encoding="utf-8")}
    rules = org_rules()
    out["AGENTS.override.md"] = "\n".join([out["AGENTS.md"].rstrip("\n"), "", mechanics("Codex")] + [t.rstrip("\n") + "\n" for _, t in rules])
    for name, text in rules:
        head = "---\ntrigger: always_on\n---\n" + MARK.format(src=f"rules/{name}") + "\n"
        parts = split_rule(text, RULE_CAP - len(head.encode('utf-8')))
        for i, part in enumerate(parts, 1):
            out[f".agents/rules/{name[:-3]}{'' if len(parts) == 1 else f'-{i}'}.md"] = head + part
    return out

def is_link(p):
    try:
        return p.is_symlink() or bool(getattr(os.stat(p, follow_symlinks=False), 'st_file_attributes', 0) & 0x400)   # 0x400: a junction
    except OSError:
        return False

def make_link(src, dst):
    if windows():
        import _winapi
        _winapi.CreateJunction(str(src), str(dst))   # no admin right needed, unlike a symlink
    else:
        os.symlink(src, dst, target_is_directory=True)

