    return json.dumps({
      "guard": {"enabled": True, "PreToolUse": [{"matcher": "run_command", "hooks": [hook(GUARD)]}]},
      "kit-health": {"enabled": True, "SessionStart": [hook(HEALTH), clean]}}, indent=2) + "\n"

