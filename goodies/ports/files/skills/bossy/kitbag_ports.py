# ---- hooks: hook wiring, exec policy
def hook_cmd(spec, kit):
    """No double quotes: agy's cmd /c hands them to pwsh as part of the path. A path with a space: -Command & '<path>'."""
    script, verb, _ = spec
    path = f'{kit}/skills/{script}'
    if re.search(r"[\s'&]", path):
        code = base64.b64encode(f"& '{path.replace(chr(39), chr(39) * 2)}' {verb}".encode('utf-16-le')).decode()
        return f"{PWSH.replace('-File ', '-EncodedCommand ')}{code}"
    return f'{PWSH}{path} {verb}'

def detached(cmd, windows):
    """agy runs hooks synchronously: the slow cleanup starts hidden in the background and the hook prints {} at once."""
    if windows:
        inner = cmd.split(' ', 1)[1].replace("'", "''")
        return f"pwsh -NoProfile -NonInteractive -WindowStyle Hidden -Command Start-Process pwsh -WindowStyle Hidden -ArgumentList '{inner}'; '{{}}'"
    return f"nohup {cmd} >/dev/null 2>&1 & echo {{}}"   # agy runs it with sh -c

def codex_config_text(kit=".claude"):
    """Codex project config: the hooks (cleanup async), KIT_TOOL for kit scripts, room for AGENTS.override.md."""
    toml = ["# Generated by kitbag.py port from settings.json; the logic lives in crafty.ps1 / bossy.ps1.",
      "project_doc_max_bytes = 65536", "", "[shell_environment_policy]", 'set = { KIT_TOOL = "codex" }', "",
      "[[hooks.PreToolUse]]", 'matcher = "^(Bash|apply_patch)$"', "", "[[hooks.PreToolUse.hooks]]", 'type = "command"',
      f"command = '''{hook_cmd(GUARD, kit)}'''", f"timeout = {GUARD[2]}"]
    for spec in (HEALTH, CLEANUP):
        toml += ["", "[[hooks.SessionStart]]", 'matcher = "*"', "", "[[hooks.SessionStart.hooks]]", 'type = "command"',
          f"command = '''{hook_cmd(spec, kit)}'''", f"timeout = {spec[2]}"] + (["async = true"] if spec is CLEANUP else [])
    return "\n".join(toml) + "\n"

def gravity_hooks_text(kit=".claude", windows=None):
    """agy hooks.json; windows None = the kit copy (cleanup not detached: the workspace copy is per OS)."""
    hook = lambda spec, cmd=None: {"type": "command", "command": cmd or hook_cmd(spec, kit), "timeout": spec[2]}
