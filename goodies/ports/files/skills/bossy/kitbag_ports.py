CLUTTER = ['Thumbs.db', 'desktop.ini', '.DS_Store', '*.swp', '*~', '*.bak', '*.orig', '*.log', '*.tmp', '*.temp',
  'tmp/', 'temp/', 'cache/', 'log/', 'logs/', 'sessions/', 'history*']   # ports.clutter replaces it; `name/` = a folder

def ports_conf():
    """kit.local.json `ports` over the defaults (targets both, clutter CLUTTER)."""
    return {'targets': 'both', 'clutter': CLUTTER, **(local_config(str(KIT), 'kit.local.json').get('ports') or {})}

def port_targets(conf):
    v = str(conf.get('targets') or 'both').lower()
    if v not in TARGETS:
        print(f"kitbag port: ports.targets '{v}' is not none | codex | antigravity | both: both")
    return TARGETS.get(v, TARGETS['both'])

def owner(rel):
    """The target a workspace path serves; None = both (AGENTS.md). Codex reads its skills from .agents/skills."""
    if rel == 'AGENTS.md':
        return None
    return 'codex' if rel.split('/')[0] in ('.codex', 'AGENTS.override.md') or rel.startswith('.agents/skills/') else 'antigravity'

def deploy_plan(on):
    """{workspace path: bytes} a deploy writes for the targets on."""
    out = {}
    for name in ('.codex', '.agents'):
        src = KIT / name
        out.update({f'{name}/{p.relative_to(src).as_posix()}': p.read_bytes() for p in (src.rglob('*') if src.exists() else []) if p.is_file()})
    out.update({r: t.encode('utf-8') for r, t in workspace_files().items()})
    return {r: b for r, b in out.items() if (owner(r) in on if owner(r) else bool(on))}

def manifest_file():
    """<state>/ports-deployed.json: {files: {path: sha256}} of the last deploy (a file still matching it is the kit's)."""
    return Path(osp.join(KIT, MAP['stateDir'], (MAP['durable'].get('ports-deployed') or 'ports-deployed.json')))

def ws_files(d):
    """Files under a workspace port folder, never through a link (.agents/skills/<name> point into the kit)."""
    for root, dirs, fs in os.walk(d):
        dirs[:] = [x for x in dirs if not is_link(Path(root) / x)]
        yield from (Path(root) / f for f in fs)

def ws_dirs(d):
    """Folders under d, links included but never entered."""
    for root, dirs, _ in os.walk(d):
        yield from [Path(root) / x for x in dirs]
        dirs[:] = [x for x in dirs if not is_link(Path(root) / x)]

def is_clutter(rel, size, globs):
    """OS, editor, log, cache, temp, session files and empty files: never a user's own (ports.clutter)."""
    parts = rel.lower().split('/')
    return size == 0 or any(any(fnmatch.fnmatch(d, g.lower().rstrip('/')) for d in parts[:-1]) or (not g.endswith('/') and fnmatch.fnmatch(parts[-1], g.lower())) for g in globs)

def leftovers(on, plan):
    """(kit-written workspace files the plan no longer has, user files in a deselected target's folder)."""
    every = deploy_plan(TARGETS['both'])
    known = (load_json(str(manifest_file()))[0] or {}).get('files') or {}
    gen, user = [], []
    cand = [WORKSPACE / r for r in ('AGENTS.md', 'AGENTS.override.md', 'GEMINI.md')] + [p for d in ('.codex', '.agents') for p in ws_files(WORKSPACE / d)]
    for p in cand:
        rel = p.relative_to(WORKSPACE).as_posix()
        if rel in plan or not p.is_file():
            continue
        b = p.read_bytes()
        if every.get(rel) == b or known.get(rel) == hashlib.sha256(b).hexdigest() or any(m in b.decode('utf-8', 'replace').lower() for m in GEN_MARKS):
            gen.append(p)
        elif owner(rel) and owner(rel) not in on:
            user.append(p)
    return gen, user

def port_deploy(quiet=False):
    """The CLIs read the session cwd's tree, never .claude: copy the chosen targets' ports there (absolute hooks, skill links,
    org rules) and remove what a deselected target or a removed source left, kit-written files only."""
    if KIT.name != '.claude':
        print(f"not deployed: {KIT} is not a workspace's .claude folder (the ports inside the kit are updated)")
        return
    conf = ports_conf()
    on = port_targets(conf)
    plan = deploy_plan(on)
    gen, user = leftovers(on, plan)
    for p in gen:
        p.unlink()
    links = WORKSPACE / '.agents' / 'skills'
    want = skill_links() if 'codex' in on else {}
    for p in links.iterdir() if links.is_dir() else []:   # a link only: os.rmdir / unlink never touch the skill it points to
        if is_link(p) and (p.name not in want or Path(os.path.realpath(p)) != want[p.name].resolve()):
            os.rmdir(p) if windows() else p.unlink()
    authored = [p for p in user if not is_clutter(p.relative_to(WORKSPACE).as_posix(), p.stat().st_size, conf.get('clutter') or [])]
    for name, t in (('.codex', 'codex'), ('.agents', 'antigravity')):
        d = WORKSPACE / name
        if not d.is_dir():
            continue
        real = [p for p in authored if d in p.parents]
        if t not in on and not (name == '.agents' and 'codex' in on) and not real and not any(is_link(x) for x in ws_dirs(d)):
            shutil.rmtree(d)   # a deselected target's folder: nothing authored left (clutter goes with it)
            gen.append(d)
            continue
        for sub in sorted((x for x in ws_dirs(d) if not is_link(x)), key=lambda x: -len(x.parts)):
            with contextlib.suppress(OSError):
                sub.rmdir()   # a retired folder (a removed agent's) goes once empty
    for rel, b in plan.items():
        t = WORKSPACE / rel
        t.parent.mkdir(parents=True, exist_ok=True)
        t.write_bytes(b)
    for n, src in want.items():
        links.mkdir(parents=True, exist_ok=True)
        if not (links / n).exists():
            make_link(src, links / n)
    for base in (WORKSPACE / ".agents", KIT):   # the forwarders the relative hook paths needed: only those files, then empty folders
        for f in (base / ".claude" / "skills").glob("*/*.ps1"):
            if f.stat().st_size < 400 and f.read_text(encoding='utf-8', errors='replace').startswith("& '"):
                f.unlink()
                for d in (f.parent, f.parent.parent, f.parent.parent.parent):
                    with contextlib.suppress(OSError):
                        d.rmdir()
    mf = manifest_file()
    mf.parent.mkdir(parents=True, exist_ok=True)
    mf.write_text(json.dumps({'schemaVersion': 1, 'files': {r: hashlib.sha256(b).hexdigest() for r, b in plan.items()}}, indent=1), encoding='utf-8')
    exclude_in_workspace(sorted(set(plan) | {".agents/", ".codex/"}))
    top = {}
    for p in gen:   # one entry per root file or folder, with its file count
        parts = p.relative_to(WORKSPACE).parts
        k = parts[0] + ('/' if parts[0] in ('.codex', '.agents') else '')
        top[k] = top.get(k, 0) + (len(parts) > 1)
    kept = [p.relative_to(WORKSPACE).as_posix() for p in authored if p.exists()]
    if quiet and not (top or kept):
        return
    print(f"ports {'+'.join(on) or 'none'} -> {WORKSPACE}: {len(plan)} file(s), {len(want)} skill link(s); removed: "
      f"{', '.join(k + (f' ({n} files)' if n else '') for k, n in sorted(top.items())) or 'nothing'}"
      + (f"; kept (not kit-written): {', '.join(kept)}" if kept else ''))

def exclude_in_workspace(paths):
    """A workspace that is itself a git repo never commits the generated copies (they hold the org rules)."""
    if not (WORKSPACE / '.git').exists():
        return
    import subprocess
    r = subprocess.run(['git', '-C', str(WORKSPACE), 'rev-parse', '--git-path', 'info/exclude'], capture_output=True, text=True, timeout=30)
    if r.returncode:
        return
    ex = Path(r.stdout.strip()) if Path(r.stdout.strip()).is_absolute() else WORKSPACE / r.stdout.strip()
    have = ex.read_text(encoding='utf-8').splitlines() if ex.exists() else []
    add = [f'/{p}' for p in paths if f'/{p}' not in have]
    if add:
        ex.parent.mkdir(parents=True, exist_ok=True)
        ex.write_text('\n'.join(have + ['# kit ports (kitbag.py port)'] + add) + '\n', encoding='utf-8')

def deployed_stale():
    """Workspace copies a fresh deploy would change (write, remove, link); [] when the kit is no installed <workspace>/.claude."""
    if KIT.name != '.claude':
        return []
    conf = ports_conf()
    on = port_targets(conf)
    plan = deploy_plan(on)
    grp = lambda r: r.split('/')[0] + '/' if '/' in r and not r.startswith('.agents/rules/') else r
    bad = [grp(r) for r, b in plan.items() if not (WORKSPACE / r).is_file() or (WORKSPACE / r).read_bytes() != b]
    gen, user = leftovers(on, plan)
    bad += [f'{grp(p.relative_to(WORKSPACE).as_posix())} (no source or target off)' for p in gen]
    links = WORKSPACE / '.agents' / 'skills'
    want = skill_links() if 'codex' in on else {}
    bad += [f'.agents/skills/{n} (link)' for n, s in want.items() if not (links / n).exists() or Path(os.path.realpath(links / n)) != s.resolve()]
    bad += [f'.agents/skills/{p.name} (link, target off)' for p in (links.iterdir() if links.is_dir() else []) if is_link(p) and p.name not in want]
    for name, t in (('.codex', 'codex'), ('.agents', 'antigravity')):
        d = WORKSPACE / name
        if d.is_dir() and t not in on and not (name == '.agents' and 'codex' in on) and not any(
                d in p.parents and not is_clutter(p.relative_to(WORKSPACE).as_posix(), p.stat().st_size, conf.get('clutter') or []) for p in user):
            bad.append(f'{name}/ (target off)')
    return sorted(set(bad))

def check_stale():
    """Stale port paths: every port is generated into a temp copy and compared by content."""
    g = globals()
    outs = ("CODEX_AGENTS", "GRAVITY_AGENTS", "CODEX_CONFIG", "CODEX_RULES", "GRAVITY_HOOKS", "GRAVITY_SKILLS", "CODEX_WORKFLOWS", "GRAVITY_WORKFLOWS")
    real = {name: g[name] for name in outs}
    stale = []
    with tempfile.TemporaryDirectory() as tmp:
        g.update({name: Path(tmp) / real[name].relative_to(KIT) for name in outs})
        try:
            with contextlib.redirect_stdout(io.StringIO()):
                port_agents()
                port_hooks()
                port_workflows()
        finally:
            g.update(real)
        made = set()
        for f in Path(tmp).rglob("*"):
            if f.is_file():
                rel = f.relative_to(tmp).as_posix()
                made.add(rel)
                if not (KIT / rel).exists() or (KIT / rel).read_text(encoding="utf-8") != f.read_text(encoding="utf-8"):
                    stale.append(rel)
        for d in (CODEX_AGENTS, GRAVITY_AGENTS, CODEX_WORKFLOWS, GRAVITY_WORKFLOWS):
            stale += [p.relative_to(KIT).as_posix() + ' (no source)' for p in (d.glob('*') if d.exists() else [])
              if p.is_file() and p.relative_to(KIT).as_posix() not in made]
    old = KIT / '.agents' / 'workflows'
    stale += [p.relative_to(KIT).as_posix() + ' (no source)' for p in (old.glob('*.md') if old.exists() else [])]
    gm = KIT / 'GEMINI.md'
    if not gm.exists() or gm.read_text(encoding='utf-8') != mechanics("Antigravity"):
        stale.append('GEMINI.md')
    stale += [f'{x} (workspace copy)' for x in deployed_stale()]
    return sorted(set(stale))

# ---- command: port [--check | --deploy]
def cmd_port(a):
    if '--check' in a:
        stale = check_stale()
        if stale:
            print(f"kitbag port: stale or missing ports: {stale}; run 'python -X utf8 skills/bossy/kitbag.py port'")
        return 1 if stale else 0
    if '--deploy' in a:   # post-merge, health: the workspace copies only, never a tracked kit file
        port_deploy(quiet=True)
        return 0
    write_characters(str(KIT))
    port_agents()
    port_hooks()
    port_workflows()
    shutil.rmtree(KIT / '.agents' / 'workflows', ignore_errors=True)   # the old procedure docs (agy: run_workflow scripts now)
    write_port(KIT / 'GEMINI.md', mechanics("Antigravity"))
    port_deploy()
    return 0

COMMANDS = {'port': cmd_port}
