# ---- deploy: the workspace copies, staleness
def windows():
    return os.name == 'nt'

def org_rules():
    """[(file name, text)] of the org rules (rules/*.local.md; local only, never pushed)."""
    return [(p.name, p.read_text(encoding='utf-8').replace('\r\n', '\n')) for p in sorted((KIT / 'rules').glob('*.local.md'))]

def split_rule(text, cap):
    """Chunks of whole lines, each <= cap UTF-8 bytes."""
    parts, cur = [], ''
    for line in text.splitlines(keepends=True):
        if cur and len((cur + line).encode('utf-8')) > cap:
            parts.append(cur)
            cur = ''
        cur += line
    return parts + ([cur] if cur else [])

def workspace_files():
    """{workspace path: text} the deploy writes besides the .codex / .agents copies."""
    kit = KIT.as_posix()
    out = {".codex/config.toml": codex_config_text(kit), ".agents/hooks.json": gravity_hooks_text(kit, windows()),
      "GEMINI.md": (KIT / "GEMINI.md").read_text(encoding="utf-8"), "AGENTS.md": (KIT / "AGENTS.md").read_text(encoding="utf-8")}
    rules = org_rules()
    out["AGENTS.override.md"] = "\n".join([out["AGENTS.md"].rstrip("\n"), "", mechanics("Codex")] + [t.rstrip("\n") + "\n" for _, t in rules])
    for name, text in rules:
        head = "---\ntrigger: always_on\n---\n" + MARK.format(src=f"rules/{name}") + "\n"
        parts = split_rule(text, RULE_CAP - len(head.encode('utf-8')))
        for i, part in enumerate(parts, 1):
            out[f".agents/rules/{name[:-3]}{'' if len(parts) == 1 else f'-{i}'}.md"] = head + part
    return out

def is_link(p):
    return p.is_symlink() or (hasattr(os.path, 'isjunction') and os.path.isjunction(p))

def make_link(src, dst):
    if windows():
        import _winapi
        _winapi.CreateJunction(str(src), str(dst))   # no admin right needed, unlike a symlink
    else:
        os.symlink(src, dst, target_is_directory=True)

def skill_links():
    """{link name: kit skill dir} for every skill (installed goodies and local skills too)."""
    return {p.parent.name: p.parent for p in sorted((KIT / 'skills').glob('*/SKILL.md'))}

def generated_rules(d):
    return [p for p in d.glob('*.md') if MARK.split('{')[0] in p.read_text(encoding='utf-8', errors='replace')[:300]] if d.exists() else []

def port_deploy():
    """The CLIs read the session cwd's tree, never .claude: copy the ports there, absolute hooks, skill links, org rules."""
    if KIT.name != '.claude':
        print(f"not deployed: {KIT} is not a workspace's .claude folder (the ports inside the kit are updated)")
        return
    for name in (".codex", ".agents"):
        src_dir, dst_dir = KIT / name, WORKSPACE / name
        for p in stale_generated(src_dir, dst_dir):
            p.unlink()
            with contextlib.suppress(OSError):
                p.parent.rmdir()   # a retired folder (the old .agents/workflows) goes once empty
        for p in src_dir.rglob('*'):
            if p.is_file():
                t = dst_dir / p.relative_to(src_dir)
                t.parent.mkdir(parents=True, exist_ok=True)
                shutil.copyfile(p, t)
    for p in generated_rules(WORKSPACE / '.agents' / 'rules'):
        p.unlink()
    files = workspace_files()
    for rel, text in files.items():
        write_port(WORKSPACE / rel, text)
    links = WORKSPACE / '.agents' / 'skills'
    links.mkdir(parents=True, exist_ok=True)
    want = skill_links()
    for p in links.iterdir():   # a link only: os.rmdir / unlink never touch the skill it points to
        if is_link(p) and (p.name not in want or Path(os.path.realpath(p)) != want[p.name].resolve()):
            os.rmdir(p) if windows() else p.unlink()
    for n, src in want.items():
        if not (links / n).exists():
            make_link(src, links / n)
    for base in (WORKSPACE / ".agents", KIT):   # the forwarders the relative hook paths needed: only those files, then empty folders
        for f in (base / ".claude" / "skills").glob("*/*.ps1"):
            if f.stat().st_size < 400 and f.read_text(encoding='utf-8', errors='replace').startswith("& '"):
                f.unlink()
                for d in (f.parent, f.parent.parent, f.parent.parent.parent):
                    with contextlib.suppress(OSError):
                        d.rmdir()
    exclude_in_workspace(sorted(set(files) | {".agents/", ".codex/"}))
    print(f"deployed -> {WORKSPACE}: .codex/, .agents/ ({len(want)} skill links, {len(org_rules())} org rule file(s)), "
      "AGENTS.md, AGENTS.override.md, GEMINI.md")

def exclude_in_workspace(paths):
    """A workspace that is itself a git repo never commits the generated copies (they hold the org rules)."""
    ex = WORKSPACE / '.git' / 'info' / 'exclude'
    if not (WORKSPACE / '.git').is_dir():
        return
    have = ex.read_text(encoding='utf-8').splitlines() if ex.exists() else []
    add = [f'/{p}' for p in paths if f'/{p}' not in have]
    if add:
        ex.parent.mkdir(parents=True, exist_ok=True)
        ex.write_text('\n'.join(have + ['# kit ports (kitbag.py port)'] + add) + '\n', encoding='utf-8')

def stale_generated(src, dst):
    """Workspace ports in dst/agents, dst/workflows or dst/kit-workflows with no kit counterpart (a removed agent / workflow)."""
    if not dst.exists():
        return []
    have = {p.relative_to(src).as_posix() for p in src.rglob('*') if p.is_file()} if src.exists() else set()
    return [p for p in dst.rglob('*') if p.is_file() and p.relative_to(dst).parts[0] in ('agents', 'workflows', 'kit-workflows')
      and p.suffix in ('.toml', '.md', '.py') and p.relative_to(dst).as_posix() not in have]

def deployed_stale():
    """Workspace copies that differ from a fresh deploy; [] when the kit is no installed <workspace>/.claude."""
    if KIT.name != '.claude':
        return []
    bad = []
    files = workspace_files()
    for name in ('.codex', '.agents'):
        src, dst = KIT / name, WORKSPACE / name
        a = {p.relative_to(src).as_posix(): p.read_bytes() for p in src.rglob('*') if p.is_file()} if src.exists() else {}
        a = {r: v for r, v in a.items() if f'{name}/{r}' not in files}
        b = {r: (dst / r).read_bytes() for r in a if (dst / r).is_file()}
        if a != b or stale_generated(src, dst):
            bad.append(name + '/')
    for rel, text in files.items():
        p = WORKSPACE / rel
        if not p.is_file() or p.read_text(encoding='utf-8') != text:
            bad.append(rel)
    want = {r for r in files if r.startswith('.agents/rules/')}
    bad += [f'.agents/rules/{p.name} (no source)' for p in generated_rules(WORKSPACE / '.agents' / 'rules') if f'.agents/rules/{p.name}' not in want]
    links = WORKSPACE / '.agents' / 'skills'
    bad += [f'.agents/skills/{n} (link)' for n, s in skill_links().items()
      if not (links / n).exists() or Path(os.path.realpath(links / n)) != s.resolve()]
    return bad

def check_stale():
    """Stale port paths: every port is generated into a temp copy and compared by content."""
    g = globals()
    outs = ("CODEX_AGENTS", "GRAVITY_AGENTS", "CODEX_CONFIG", "CODEX_RULES", "GRAVITY_HOOKS", "GRAVITY_SKILLS", "CODEX_WORKFLOWS", "GRAVITY_WORKFLOWS")
    real = {name: g[name] for name in outs}
    stale = []
    with tempfile.TemporaryDirectory() as tmp:
        g.update({name: Path(tmp) / real[name].relative_to(KIT) for name in outs})
        try:
            with contextlib.redirect_stdout(io.StringIO()):
                port_agents()
                port_hooks()
                port_workflows()
        finally:
            g.update(real)
        made = set()
        for f in Path(tmp).rglob("*"):
            if f.is_file():
                rel = f.relative_to(tmp).as_posix()
                made.add(rel)
                if not (KIT / rel).exists() or (KIT / rel).read_text(encoding="utf-8") != f.read_text(encoding="utf-8"):
                    stale.append(rel)
        for d in (CODEX_AGENTS, GRAVITY_AGENTS, CODEX_WORKFLOWS, GRAVITY_WORKFLOWS):
            stale += [p.relative_to(KIT).as_posix() + ' (no source)' for p in (d.glob('*') if d.exists() else [])
              if p.is_file() and p.relative_to(KIT).as_posix() not in made]
    old = KIT / '.agents' / 'workflows'
    stale += [p.relative_to(KIT).as_posix() + ' (no source)' for p in (old.glob('*.md') if old.exists() else [])]
    gm = KIT / 'GEMINI.md'
    if not gm.exists() or gm.read_text(encoding='utf-8') != mechanics("Antigravity"):
        stale.append('GEMINI.md')
    stale += [f'{x} (workspace copy)' for x in deployed_stale()]
    return sorted(set(stale))

# ---- command: port [--check]
def cmd_port(a):
    if '--check' in a:
        stale = check_stale()
        if stale:
            print(f"kitbag port: stale or missing ports: {stale}; run 'python -X utf8 skills/bossy/kitbag.py port'")
        return 1 if stale else 0
    write_characters(str(KIT))
    port_agents()
    port_hooks()
    port_workflows()
    shutil.rmtree(KIT / '.agents' / 'workflows', ignore_errors=True)   # the old procedure docs (agy: run_workflow scripts now)
    write_port(KIT / 'GEMINI.md', mechanics("Antigravity"))
    port_deploy()
    return 0

