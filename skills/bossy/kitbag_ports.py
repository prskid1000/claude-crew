GRAVITY_TOOL_MAP = {"Read": ["view_file"], "Grep": ["grep_search"], "Glob": ["find_by_name", "list_dir"], "Bash": ["run_command"],
  "PowerShell": ["run_command"], "Write": ["write_to_file"], "Edit": ["replace_file_content", "multi_replace_file_content"],
  "Monitor": ["manage_task"], "TaskStop": ["manage_task"], "Agent": ["invoke_subagent"], "ToolSearch": []}

def gravity_tools(tools):
    """Antigravity's `tools:` allow-list for a Claude Code tools line, or None (a tool it cannot name: every tool loads)."""
    names = [x.strip() for x in (tools or "").split(",") if x.strip()]
    if not names or any(x not in GRAVITY_TOOL_MAP and not x.startswith("mcp__") for x in names):
        return None
    # call_mcp_tool always: MCP grants are org-local (kit.local.json tools.roles), never in the tracked list
    return list(dict.fromkeys([g for x in names if not x.startswith("mcp__") for g in GRAVITY_TOOL_MAP[x]] + ["call_mcp_tool"]))

def write_gravity(name, fields, body):
    # tools: the mapped allow-list (https://antigravity.google/docs/subagents/), else unset = all tools; the guard hook enforces both
    gt = gravity_tools(fields.get("tools"))
    head = [f"name: {name}", f'description: {json.dumps(fields["description"], ensure_ascii=False)}', "subagent: true",
      "mainAgent: false", "model: inherit", "commandExecutionPolicy: auto"] + ([f"tools: [{', '.join(gt)}]"] if gt else [])
    note = (f"\n> Ported note: the Claude Code definition restricts tools to `{fields['tools']}` (MCP servers only when kit.local.json "
      "tools.roles grants them); here " + ("the tools list above holds their Antigravity names; every MCP server is reachable (call_mcp_tool): call no other."
      if gt else "all tools and MCP servers load (one has no Antigravity name): call no other.") + " The kit guard hook blocks what it blocks for every agent.\n") if fields.get("tools") else ""
    write_port(GRAVITY_AGENTS / f"{name}.md", "---\n" + "\n".join(head) + "\n---\n" + note + "\n" + body.strip() + "\n" + GRAVITY_TOOL)

def prune(folder, suffix, keep):
    """Drop a port the kit no longer generates (a removed or renamed agent / workflow)."""
    for p in folder.glob('*' + suffix) if folder.exists() else []:
        if p.stem not in keep:
            p.unlink()

def port_agents():
    made = set()
    for src in sorted((KIT / "agents").glob("*.md")):
        fields, body = agent_parts(src.read_text(encoding="utf-8").replace("\r\n", "\n"))
        name = fields.get("name", src.stem)
        if (gen := role_tools(name, str(KIT))):   # the tracked allowlist: an installed kit's grants (org servers) never reach a port
            fields["tools"] = gen
        write_codex(name, fields, body.rstrip("\n") + "\n" + AGENT_DECIDE)
        write_gravity(name, fields, body.rstrip("\n") + "\n" + AGENT_DECIDE)
        made.add(name)
    prune(CODEX_AGENTS, '.toml', made)
    prune(GRAVITY_AGENTS, '.md', made)
    print(f"ported {len(made)} agent(s) -> .codex/agents/*.toml, .agents/agents/*.md")

# ---- hooks: hook wiring, exec policy
def found_cmd(rel, node=False):
    """A relative kit (the tracked copy): the first <dir> from the cwd upward holding <kit>/skills/crafty/crafty.ps1 (one kit for
    every hook), so a hook run from a subfolder or the kit itself finds it with no org path in a tracked file; none -> exit 2,
    fail-closed. Encoded: cmd /c and sh -c alike. A child pwsh -File: stdin inherited, its exit code as -File gives it."""
    run = "[Console]::In.ReadToEnd() | & node $f" if node else "Invoke-Expression ('& pwsh -NoProfile -NonInteractive -ExecutionPolicy Bypass -File $f ' + $v)"
    code = (f"$s, $v = '{rel}' -split ' ', 2; $m = '{rel.split('/skills/')[0]}/skills/crafty/crafty.ps1'; $d = $PWD.Path; "
      "while ($d -and -not (Test-Path -LiteralPath (Join-Path $d $m))) { $d = Split-Path $d }; "
      "if (-not $d) { [Console]::Error.WriteLine('kit hook: ' + $s + ' not found in ' + $PWD.Path + ' or above: start in the "
      "workspace, or deploy ports.targets (absolute paths)'); exit 2 }; "
      f"$f = Join-Path $d $s; {run}; exit $LASTEXITCODE")
    return f"pwsh -NoProfile -NonInteractive -ExecutionPolicy Bypass -EncodedCommand {base64.b64encode(code.encode('utf-16-le')).decode()}"

def hook_cmd(spec, kit):
    """No double quotes: agy's cmd /c hands them to pwsh as part of the path. A path with a space: -Command & '<path>'."""
    script, verb, _ = spec
    path = f'{kit}/skills/{script}'
    if not re.match(r'([A-Za-z]:)?[/\\]', kit):   # the tracked copy: no absolute kit path
        return found_cmd(f'{path} {verb}')
    if re.search(r"[\s'&]", path):
        code = base64.b64encode(f"& '{path.replace(chr(39), chr(39) * 2)}' {verb}".encode('utf-16-le')).decode()
        return f"{PWSH.replace('-File ', '-EncodedCommand ')}{code}"
    return f'{PWSH}{path} {verb}'

def node_hook_cmd(spec, kit):
    """node <path>; a path with a space or quote: pwsh pipes stdin to it (no double quotes, as hook_cmd)."""
    path = f'{kit}/skills/{spec[0]}'
    if not re.match(r'([A-Za-z]:)?[/\\]', kit):   # the tracked copy: no absolute kit path
        return found_cmd(path, node=True)
    if re.search(r"[\s'&]", path):
        code = base64.b64encode(f"[Console]::In.ReadToEnd() | & node '{path.replace(chr(39), chr(39) * 2)}'".encode('utf-16-le')).decode()
        return f"pwsh -NoProfile -NonInteractive -EncodedCommand {code}"
    return f'node {path}'

def detached(cmd, windows):
    """agy runs hooks synchronously: the slow cleanup starts hidden in the background and the hook prints {} at once."""
    if windows:
        inner = cmd.split(' ', 1)[1].replace("'", "''")
        return f"pwsh -NoProfile -NonInteractive -WindowStyle Hidden -Command Start-Process pwsh -WindowStyle Hidden -ArgumentList '{inner}'; '{{}}'"   # arch-ok: Windows branch
    return f"nohup {cmd} >/dev/null 2>&1 & echo {{}}"   # agy runs it with sh -c

