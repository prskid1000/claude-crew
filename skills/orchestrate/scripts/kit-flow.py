#!/usr/bin/env python3
"""Render the kit's trigger flow as one self-contained HTML page (no external libraries, works from file://).

  python kit-flow.py [<kit .claude dir>] [--out <file.html>] [--watch] [--open]

Default kit dir: the .claude folder this script lives in. Default output: <runtime>/kit-flow.html, where runtime is
$CLAUDE_RUNTIME or <workspace>/.claude-runtime (the folder next to .claude). --watch regenerates whenever a kit file is
added, removed or changed (poll every 2 s): use it while editing the kit; the page's "Live" toggle reloads it.
It is also regenerated by the SessionStart hook (kit-health.ps1 -Flow, async), by every kit-lint.py run and by sync-kit.ps1.

Tabs: Flow (one swimlane per trigger group, collapsed to doc/script chips; hover draws every link on top), Triggers (a card
per skill, workflow, agent type, hook and scoped rule with its Load when / Not when / Hands off to or Spawned by / Not for),
Router & events (the always-loaded tables, each row linked to its target), Files (sortable, filterable) and Issues.
Graph, reach and issues come from kitgraph_lib.py, the module kit-lint.py uses, so the page and the lint never disagree.
Page markup: kit-flow.template.html next to this script (the __DATA__ placeholder receives the JSON built here).
"""
import json, os, re, subprocess, sys, time

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import kitgraph_lib as lib  # noqa: E402

TEMPLATE = os.path.join(HERE, 'kit-flow.template.html')


def default_out(kit):
    rt = os.environ.get('CLAUDE_RUNTIME') or os.path.join(os.path.dirname(kit), '.claude-runtime')
    return os.path.join(rt, 'kit-flow.html')


def args():
    a = sys.argv[1:]
    out = a[a.index('--out') + 1] if '--out' in a else None
    rest = [x for i, x in enumerate(a) if not x.startswith('--') and (i == 0 or a[i - 1] != '--out')]
    kit = os.path.abspath(rest[0] if rest else os.path.join(HERE, '..', '..', '..'))
    return kit, os.path.abspath(out or default_out(kit)), '--watch' in a, '--open' in a


def page_data(k, g, problems):
    """Page model: the graph, each trigger's blocks, the router/events tables and kit-lint's problems as the issue list."""
    nodes = {f: dict(n) for f, n in g['nodes'].items()}
    for f, n in nodes.items():
        text = k.texts.get(f, '')
        if n['kind'] == 'skill':
            n['blocks'] = lib.blocks(text)
        elif n['kind'] == 'agent':
            n['blocks'] = lib.agent_blocks(lib.frontmatter(text).get('description', ''))
        elif n['kind'] == 'workflow':
            m = re.search(r"whenToUse:\s*'((?:[^'\\]|\\.)*)'", text)
            n['blocks'] = {'When to use': m.group(1)} if m else {}
    issues = [{'type': lib.ISSUE_TYPE.get(c, 'lint ' + c.lower()), 'code': c, 'id': w if w in nodes else None,
               'text': (m if w in nodes else f'{w}: {m}')} for c, w, m in problems]
    edges = g['edges']
    return {'kit': k.dir, 'generated': time.strftime('%Y-%m-%d %H:%M:%S'),
            'nodes': list(nodes.values()), 'edges': [{'s': a, 't': b, 'type': t} for (a, b), t in sorted(edges.items())],
            'tables': lib.tables(k), 'issues': issues,
            'counts': {'files': len(nodes), 'edges': len(edges),
                       'structural': sum(1 for n in nodes.values() if n['reach'] in ('entry', 'structural')), 'issues': len(issues)}}


def build(kit):
    k = lib.load(kit)
    g = lib.graph(k)
    return page_data(k, g, lib.lint(k, g))


def render(kit, out, quiet=False, data=None):
    data = data or build(kit)
    os.makedirs(os.path.dirname(out), exist_ok=True)
    blob = json.dumps(data, ensure_ascii=False).replace('</', '<\\/')
    with open(TEMPLATE, encoding='utf-8') as fh:
        page = fh.read().replace('__DATA__', blob)
    with open(out, 'w', encoding='utf-8') as fh:
        fh.write(page)
    c = data['counts']
    if not quiet:
        print(f"kit-flow: {out}  ({c['files']} files, {c['edges']} edges, {c['structural']} reached structurally, {c['issues']} issues)")
    return data


def signature(kit):
    sig = []
    for d, dirs, fs in os.walk(kit):
        dirs[:] = [x for x in dirs if x not in lib.SKIP_DIRS]
        for f in fs:
            try:
                st = os.stat(os.path.join(d, f))
                sig.append((d, f, st.st_mtime_ns, st.st_size))
            except OSError:
                pass
    return hash(tuple(sorted(sig)))


if __name__ == '__main__':
    kit, out, watch, open_it = args()
    if not os.path.isdir(kit):
        sys.exit(f'kit-flow: no such folder {kit}')
    render(kit, out)
    if open_it:
        if sys.platform.startswith('win'):
            os.startfile(out)  # type: ignore[attr-defined]  # noqa
        else:
            subprocess.run(['open' if sys.platform == 'darwin' else 'xdg-open', out], check=False)
    if watch:
        print('kit-flow: watching for changes (Ctrl+C to stop)')
        last = signature(kit)
        while True:
            time.sleep(2)
            cur = signature(kit)
            if cur != last:
                last = cur
                try:
                    render(kit, out)
                except Exception as e:  # keep watching through a half-written file
                    print('kit-flow: render failed, will retry:', e)
